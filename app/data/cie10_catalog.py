def seed_cie10_catalog(db) -> int:
    """Inserta los códigos CIE-10 oficiales en la base de datos si aún no están poblados."""
    from app.models.cie10 import Cie10Code
    existing_count = db.query(Cie10Code).filter(Cie10Code.is_custom == False).count()
    if existing_count > 50:
        return existing_count
    
    inserted = 0
    for item in OFFICIAL_CIE10_CATALOG:
        exists = db.query(Cie10Code).filter(Cie10Code.code == item["code"]).first()
        if not exists:
            new_code = Cie10Code(
                code=item["code"],
                description=item["description"],
                chapter=item.get("chapter", "General"),
                is_custom=False
            )
            db.add(new_code)
            inserted += 1
            
    if inserted > 0:
        db.commit()
    return db.query(Cie10Code).count()
